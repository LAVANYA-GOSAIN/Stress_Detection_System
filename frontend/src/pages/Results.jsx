import React, { useState } from 'react';
import { useLocation, Link, useNavigate } from 'react-router-dom';
import { 
  BarChart3, 
  ArrowLeft, 
  RefreshCw, 
  ShieldAlert, 
  Lightbulb, 
  Info,
  CheckCircle2, 
  ChevronDown, 
  ChevronUp, 
  Sparkles,
  Cpu
} from 'lucide-react';

/**
 * Results Page Component
 * Renders real machine learning predictions and class probability distributions
 * returned by the FastAPI backend, adhering strictly to discrete target classes (0, 1, 2)
 * without unverified semantic labels.
 */
export default function Results() {
  const location = useLocation();
  const navigate = useNavigate();
  const [showInputSummary, setShowInputSummary] = useState(false);

  // Extract prediction data and user inputs from navigation state
  const predictionData = location.state?.prediction;
  const userInputs = location.state?.inputs;

  // Fallback sample data if accessed directly without submitting assessment
  const isSample = !predictionData;
  const displayData = predictionData || {
    predicted_class: 1,
    probabilities: {
      0: 0.004,
      1: 0.992,
      2: 0.004,
    },
    disclaimer:
      'This prediction is generated by a machine learning model for educational purposes only and does not constitute a medical or clinical diagnosis.',
  };

  const probabilities = displayData.probabilities || { 0: 0, 1: 0, 2: 0 };
  const predictedClass = displayData.predicted_class;

  return (
    <main className="flex-1 py-12 sm:py-16 bg-[#FAF9FE]">
      <div className="max-w-4xl mx-auto px-4 sm:px-6 lg:px-8 space-y-8">
        
        {/* Navigation Breadcrumb */}
        <div className="flex items-center gap-2 text-xs sm:text-sm text-slate-500 font-medium">
          <Link to="/" className="hover:text-violet-700 flex items-center gap-1 transition-colors">
            <ArrowLeft className="w-3.5 h-3.5" />
            Home
          </Link>
          <span>/</span>
          <Link to="/assessment" className="hover:text-violet-700 transition-colors">
            Assessment
          </Link>
          <span>/</span>
          <span className="text-violet-700 font-semibold">Results Evaluation</span>
        </div>

        {/* Page Title & Intro */}
        <div className="space-y-3">
          <div className="inline-flex items-center gap-2 px-3 py-1 rounded-full bg-violet-100 text-violet-800 text-xs font-bold tracking-wide">
            <BarChart3 className="w-4 h-4 text-violet-600" />
            <span>Step 2: Model Classification Output</span>
          </div>
          <h1 className="text-3xl sm:text-4xl font-extrabold text-slate-900 tracking-tight">
            Stress Assessment Results
          </h1>
          <p className="text-base sm:text-lg text-slate-600 leading-relaxed font-normal">
            Your 20-feature input vector was evaluated using our Scikit-learn Gradient Boosting Classifier pipeline.
          </p>
        </div>

        {/* Notice for Direct Visits (Sample Mode) */}
        {isSample && (
          <div className="p-4 rounded-2xl bg-indigo-50 border border-indigo-200 text-indigo-950 text-xs sm:text-sm flex items-center justify-between gap-4">
            <div className="flex items-center gap-2.5">
              <Sparkles className="w-4 h-4 text-indigo-600 shrink-0" />
              <span>Viewing sample layout mode. Complete the 20-feature questionnaire for custom inference.</span>
            </div>
            <button
              type="button"
              onClick={() => navigate('/assessment')}
              className="shrink-0 px-3 py-1.5 rounded-xl bg-indigo-600 hover:bg-indigo-700 text-white font-semibold text-xs transition-colors"
            >
              Take Assessment
            </button>
          </div>
        )}

        {/* Primary Results Card */}
        <div className="bg-white rounded-3xl p-8 sm:p-10 border border-purple-100 shadow-sm space-y-8">
          
          {/* Top Classification Output Banner */}
          <div className="p-6 rounded-2xl bg-gradient-to-r from-violet-50 via-purple-50 to-indigo-50 border border-purple-100 flex flex-col sm:flex-row items-center justify-between gap-6">
            <div className="space-y-1 text-center sm:text-left">
              <span className="text-xs font-bold uppercase tracking-wider text-violet-600">
                Discrete Model Prediction
              </span>
              <div className="text-3xl sm:text-4xl font-extrabold text-slate-900">
                Class <span className="text-violet-700">{predictedClass}</span>
              </div>
              <p className="text-xs text-slate-500 font-normal">
                Class label assigned by Scikit-learn Gradient Boosting decision trees
              </p>
            </div>

            <div className="flex items-center gap-2 bg-white px-4 py-2.5 rounded-xl border border-purple-100 shadow-sm text-xs font-semibold text-slate-700">
              <Cpu className="w-4 h-4 text-violet-600" />
              <span>Estimated Probability: {((probabilities[predictedClass] || 0) * 100).toFixed(1)}%</span>
            </div>
          </div>

          {/* Probability Distribution Section */}
          <div className="space-y-4">
            <div className="flex items-center justify-between">
              <h2 className="text-lg font-bold text-slate-900">
                Estimated Probability Distribution
              </h2>
              <span className="text-xs text-slate-400 font-mono">
                Method: predict_proba()
              </span>
            </div>

            <div className="grid grid-cols-1 sm:grid-cols-3 gap-4">
              {[0, 1, 2].map((classId) => {
                const prob = probabilities[classId] ?? 0;
                const percentage = (prob * 100).toFixed(2);
                const isSelected = predictedClass === classId;

                return (
                  <div
                    key={classId}
                    className={`p-5 rounded-2xl border transition-all space-y-3 ${
                      isSelected
                        ? 'border-violet-300 bg-violet-50/70 shadow-sm ring-2 ring-violet-500/20'
                        : 'border-slate-200/80 bg-slate-50/50'
                    }`}
                  >
                    <div className="flex justify-between items-center text-xs font-bold">
                      <span className={isSelected ? 'text-violet-900' : 'text-slate-600'}>
                        Target Class {classId}
                      </span>
                      {isSelected && (
                        <span className="text-[10px] uppercase font-bold px-2 py-0.5 rounded-full bg-violet-200 text-violet-800">
                          Selected
                        </span>
                      )}
                    </div>

                    <div className="text-2xl font-black text-slate-900">
                      {percentage}%
                    </div>

                    <div className="h-2 w-full bg-slate-200 rounded-full overflow-hidden">
                      <div
                        className={`h-full rounded-full transition-all duration-500 ${
                          isSelected
                            ? 'bg-gradient-to-r from-violet-600 to-indigo-600'
                            : 'bg-slate-400'
                        }`}
                        style={{ width: `${Math.max(prob * 100, 2)}%` }}
                      />
                    </div>

                    <p className="text-[11px] text-slate-500">
                      Mathematical likelihood across 20 parameters
                    </p>
                  </div>
                );
              })}
            </div>
          </div>

          {/* Target Class Architecture Notice */}
          <div className="p-4 rounded-2xl bg-indigo-50/60 border border-indigo-100 text-indigo-950 space-y-2">
            <div className="flex items-center gap-2 font-bold text-xs text-indigo-900">
              <Info className="w-4 h-4 text-indigo-700" />
              <span>Scientific Class Neutrality</span>
            </div>
            <p className="text-xs text-slate-600 leading-relaxed font-normal">
              In accordance with project guidelines, target classes are represented strictly as discrete mathematical identifiers <code>0</code>, <code>1</code>, and <code>2</code>. We do not assign speculative labels (such as Low, Moderate, or High) because semantic mappings are unverified in the dataset documentation.
            </p>
          </div>

          {/* Submitted 20-Feature Summary (Accordion) */}
          {userInputs && (
            <div className="border border-slate-200 rounded-2xl overflow-hidden">
              <button
                type="button"
                onClick={() => setShowInputSummary(!showInputSummary)}
                className="w-full p-4 bg-slate-50 flex items-center justify-between text-left text-xs font-bold text-slate-800 hover:bg-slate-100 transition-colors"
              >
                <span>Inspected 20 Input Parameters</span>
                {showInputSummary ? (
                  <ChevronUp className="w-4 h-4 text-slate-500" />
                ) : (
                  <ChevronDown className="w-4 h-4 text-slate-500" />
                )}
              </button>

              {showInputSummary && (
                <div className="p-4 bg-white border-t border-slate-200 grid grid-cols-2 sm:grid-cols-4 gap-3 text-xs">
                  {Object.entries(userInputs).map(([k, v]) => (
                    <div key={k} className="p-2 rounded-lg bg-slate-50 border border-slate-100">
                      <div className="text-slate-400 text-[10px] font-mono truncate">{k}</div>
                      <div className="font-bold text-slate-800 text-sm">{v}</div>
                    </div>
                  ))}
                </div>
              )}
            </div>
          )}

          {/* Actionable Student Self-Care Recommendations */}
          <div className="space-y-4 pt-2">
            <div className="flex items-center gap-2">
              <Lightbulb className="w-5 h-5 text-amber-500" />
              <h3 className="text-base font-bold text-slate-900">
                Recommended Student Wellness Habits
              </h3>
            </div>
            
            <div className="grid grid-cols-1 sm:grid-cols-2 gap-3 text-xs sm:text-sm text-slate-600">
              <div className="flex items-start gap-2.5 p-3.5 rounded-xl bg-slate-50">
                <CheckCircle2 className="w-4 h-4 text-emerald-600 shrink-0 mt-0.5" />
                <span>Establish consistent sleep and recovery routines during study periods.</span>
              </div>
              <div className="flex items-start gap-2.5 p-3.5 rounded-xl bg-slate-50">
                <CheckCircle2 className="w-4 h-4 text-emerald-600 shrink-0 mt-0.5" />
                <span>Balance academic workloads through structured study sessions and breaks.</span>
              </div>
              <div className="flex items-start gap-2.5 p-3.5 rounded-xl bg-slate-50">
                <CheckCircle2 className="w-4 h-4 text-emerald-600 shrink-0 mt-0.5" />
                <span>Engage with student peers and campus wellness networks regularly.</span>
              </div>
              <div className="flex items-start gap-2.5 p-3.5 rounded-xl bg-slate-50">
                <CheckCircle2 className="w-4 h-4 text-emerald-600 shrink-0 mt-0.5" />
                <span>Reach out to academic advisors when experiencing acute coursework pressure.</span>
              </div>
            </div>
          </div>

          {/* Navigation Controls */}
          <div className="pt-4 border-t border-slate-100 flex flex-col sm:flex-row items-center justify-between gap-4">
            <Link
              to="/assessment"
              className="w-full sm:w-auto inline-flex items-center justify-center gap-2 px-5 py-2.5 rounded-xl text-sm font-semibold text-slate-700 bg-slate-100 hover:bg-slate-200 transition-colors"
            >
              <RefreshCw className="w-4 h-4" />
              <span>Retake Assessment</span>
            </Link>

            <Link
              to="/"
              className="w-full sm:w-auto inline-flex items-center justify-center gap-2 px-6 py-3 rounded-xl text-sm font-semibold text-white bg-gradient-to-r from-violet-600 to-indigo-600 hover:from-violet-700 hover:to-indigo-700 shadow-md shadow-violet-500/20 transition-all duration-200"
            >
              <span>Return to Homepage</span>
            </Link>
          </div>

        </div>

        {/* Dynamic Disclaimer Card from Backend */}
        <div className="p-4 rounded-2xl bg-amber-50/80 border border-amber-200 text-amber-900 text-xs flex items-start gap-3">
          <ShieldAlert className="w-4 h-4 text-amber-600 shrink-0 mt-0.5" />
          <p className="leading-relaxed">
            <strong>Mandatory Educational Notice:</strong> {displayData.disclaimer}
          </p>
        </div>

      </div>
    </main>
  );
}
